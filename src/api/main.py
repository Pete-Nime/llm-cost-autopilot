
# Import FastAPI and HTTPException for API routes and errors.
from fastapi import FastAPI, HTTPException

# Import our existing database analytics function.
from src.database.analytics import get_usage_summary

# Import Pydantic to validate incoming request data.
from pydantic import BaseModel, Field

# Import our existing intelligent routing function.
from src.router.intelligent_router import route_prompt

# Read environment variables used to control execution.
import os

# Read the current shared budget when reporting workflow costs.
import config.budget as budget_config

# Import our existing workflow that executes and logs AI requests.
from src.database.workflow_logger import run_and_log

# Import the budget threshold.
# Import the shared budget and input-size settings.
from config.budget import (
    MAX_PROMPT_CHARACTERS
)

# Import the fallback-aware budget policy.
from src.router.budget_policy import (
    is_routed_workflow_within_budget,
)

# Create our FastAPI application.
app = FastAPI(
    title="LLM Cost Autopilot API",
    description="AI model routing and cost monitoring",
    version="1.0.0",
)

# Define the information a client must send to our API.
class RoutingRequest(BaseModel):

    # Require a prompt containing between 1 and 2000 characters.
    prompt: str = Field(
        min_length=1,
       max_length=MAX_PROMPT_CHARACTERS,
    )

    # Use the original classifier unless V2 is requested.
    use_v2: bool = False

    # Set the candidate escalation threshold to 40%.
    risk_threshold: float = Field(
        default=0.40,
        ge=0.0,
        le=1.0,
    )


# Describe the response returned after AI execution.
class ExecutionResponse(BaseModel):

    # The text generated by the selected AI model.
    answer: str

    # The AI provider/model that produced the final answer.
    model: str

    # Whether a fallback model was used.
    escalated: bool

    # Number of AI provider attempts.
    attempts: int

    # Estimated API cost for the entire workflow.
    estimated_cost_usd: float

    # True when the completed workflow exceeds our budget.
    budget_exceeded: bool

# Create a simple endpoint to check whether the API works.
@app.get("/health")
def health_check():

    # Return a simple confirmation message.
    return {
        "status": "healthy",
        "service": "LLM Cost Autopilot",
    }


# Create an endpoint that returns our usage statistics.
@app.get("/analytics/summary")
def analytics_summary():

    # Read the stored usage statistics from SQLite.
    summary = get_usage_summary()

    # Return the statistics as JSON.
    return summary

# Create an endpoint that previews intelligent model routing.
@app.post("/route/preview")
def route_preview(request: RoutingRequest):

    # Remove whitespace from the beginning and end.
    cleaned_prompt = request.prompt.strip()

    # Reject prompts containing only spaces.
    if not cleaned_prompt:


        raise HTTPException(
            status_code=422,
            detail="Prompt cannot contain only whitespace.",
        )

    # Select the model using the requested classifier.
    decision = route_prompt(
        cleaned_prompt,
        use_v2=request.use_v2,
        risk_threshold=request.risk_threshold,
    )

    # Return the decision without calling an AI provider.
    return {
        "complexity": decision.complexity,
        "selected_model": decision.model_name,
        "reason": decision.reason,
        "executed": False,
    }

# Create an endpoint for executing an AI request.
@app.post("/route/execute", response_model=ExecutionResponse)
async def route_execute(request: RoutingRequest):

    # Keep real AI execution disabled unless explicitly enabled.
    if os.getenv("ENABLE_AI_EXECUTION") != "true":

        # Return HTTP 403 rather than calling an AI provider.
        raise HTTPException(
            status_code=403,
            detail="AI execution is disabled.",
        )

    # Remove unnecessary whitespace from the prompt.
    cleaned_prompt = request.prompt.strip()


    # Reject prompts containing only whitespace.
    if not cleaned_prompt:

        # Return a validation error.
        raise HTTPException(
            status_code=422,
            detail="Prompt cannot contain only whitespace.",
        )

    
    
    # Store a V2 decision only when V2 is requested.
    decision = None

    # Use the trained classifier when explicitly enabled.
    if request.use_v2:

        # Choose the model using V2 and our risk-aware policy.
        try:
            decision = route_prompt(
                cleaned_prompt,
                use_v2=True,
                risk_threshold=request.risk_threshold,
            )

        # Handle classifier failures without exposing internal details.
        except Exception:
            raise HTTPException(
                status_code=503,
                detail="AI routing is temporarily unavailable.",
            ) from None

        # Check the budget for this exact selected model.
        within_budget = is_routed_workflow_within_budget(
            prompt=cleaned_prompt,
            decision=decision,
        )

    # Preserve the original budget check for existing requests.
    else:

        # Keep the original function call unchanged.
        within_budget = is_routed_workflow_within_budget(
            prompt=cleaned_prompt,
        )

    # Block requests whose estimated workflow cost exceeds the limit.
    if not within_budget:
        raise HTTPException(
            status_code=403,
            detail="Estimated workflow cost exceeds the configured budget.",
        )


    # Attempt to run our AI workflow safely.
    try:

       
        # Pass the V2 decision through the entire workflow when enabled.
        if decision is not None:

            # Execute using the same model selected during budget checking.
            result = await run_and_log(
                cleaned_prompt,
                decision=decision,
            )

        # Preserve the original execution behavior otherwise.
        else:

            # Run the existing workflow without changing its arguments.
            result = await run_and_log(cleaned_prompt)


    # Handle unexpected failures without exposing internal details.
    except Exception:

        # Return a generic error to the API client.
        raise HTTPException(
            status_code=503,
            detail="AI execution is temporarily unavailable.",
        ) from None


    # Add the estimated costs of every AI provider attempt.
    # This includes both the initial request and any fallback request.
    total_cost_usd = sum(
        response.cost_usd
        for response in result.responses
    )


    # Return the response in a structured JSON format.
    return ExecutionResponse(
        answer=result.response.output_text,
        model=result.response.model_id,
        escalated=result.escalated,
        attempts=result.attempts,
        # Report the cost of the entire workflow, not just the final answer.
        estimated_cost_usd=total_cost_usd,
        # Compare the completed workflow cost against our shared budget.
        budget_exceeded=(
            total_cost_usd > budget_config.MAX_REQUEST_COST_USD
        ),
    )   

